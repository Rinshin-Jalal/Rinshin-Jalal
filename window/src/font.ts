for (const [ch, rows] of Object.entries(GLYPHS)) {
  if (rows.length !== 5 || rows.some((r) => r.length !== 3 || /[^#.]/.test(r))) {
    throw new Error(`font: glyph ${JSON.stringify(ch)} is not 3x5`);
  }
}

export const GLYPH_ADVANCE = 4; // 3 cells + 1 cell of spacing

/** Width of `text` in px at the given scale. */
export function textWidth(text: string, scale: number): number {
  return Math.max(0, [...text].length * GLYPH_ADVANCE - 1) * scale;
}

/**
 * SVG rects for `text` with its top-left at (x, y), each font cell `scale` px.
 * Horizontal runs within a glyph row are merged to keep the SVG small.
 */
export function pixelText(text: string, x: number, y: number, scale: number, fill: string): string {
  const out: string[] = [];
  [...text.toLowerCase()].forEach((ch, i) => {
    const rows = GLYPHS[ch] ?? GLYPHS["?"];
    const gx = x + i * GLYPH_ADVANCE * scale;
    rows.forEach((row, r) => {
      let col = 0;
      while (col < 3) {
        if (row[col] !== "#") { col++; continue; }
        let end = col;
        while (end + 1 < 3 && row[end + 1] === "#") end++;
        out.push(`<rect x="${gx + col * scale}" y="${y + r * scale}" width="${(end - col + 1) * scale}" height="${scale}"/>`);
        col = end + 1;
      }
    });
  });
  return `<g fill="${fill}">${out.join("")}</g>`;
}
